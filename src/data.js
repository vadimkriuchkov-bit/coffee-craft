export function shopStatus(shop, now = new Date()) {
  if (!shop.hours) return { open: null, text: 'Часы уточняются' };
  // время по Москве
  const msk = new Date(now.toLocaleString('en-US', { timeZone: 'Europe/Moscow' }));
  const day = (msk.getDay() + 6) % 7; // пн = 0
  const h = msk.getHours() + msk.getMinutes() / 60;
  const [o, c] = shop.hours[day];
  if (h >= o && h < c) {
    const left = Math.round((c - h) * 60);
    return {
      open: true,
      text: left <= 60 ? `Открыто · закроется через ${left} мин` : `Открыто до ${c}:00`,
    };
  }
  const nextOpen = h < o ? o : shop.hours[(day + 1) % 7][0];
  return { open: false, text: `Закрыто · откроется в ${nextOpen}:00` };
}

